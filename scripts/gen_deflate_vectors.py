#!/usr/bin/env python3
"""Generate the DEFLATE vectors the deflate package is tested against.

The streams a permessage-deflate endpoint has to read are produced by zlib, not
by this library, so the vectors are produced by zlib too: one file of cases,
each a list of wire segments (the empty stored block's four-octet tail already
stripped, as RFC 7692 §7.2.1 leaves them) and the message each segment carries.

The output is committed; CI only runs what this wrote.
"""

import random
import zlib

OUT = "src/deflate/vectors.mbt"


def segments(bits, takeover, messages, level=6):
    """Compress each message, keeping or dropping the window between them."""
    comp = zlib.compressobj(level, zlib.DEFLATED, -bits)
    out = []
    for message in messages:
        if not takeover:
            comp = zlib.compressobj(level, zlib.DEFLATED, -bits)
        if level == 0:
            # A stored block, ended by the empty block a sync flush appends.
            data = comp.compress(message) + comp.flush(zlib.Z_SYNC_FLUSH)
        else:
            data = comp.compress(message) + comp.flush(zlib.Z_SYNC_FLUSH)
        if not data.endswith(b"\x00\x00\xff\xff"):
            raise SystemExit("zlib did not end with a sync flush")
        out.append(data[:-4])
    return out


def words(n, seed=1):
    rnd = random.Random(seed)
    pool = [b"alpha", b"bravo", b"charlie", b"delta", b"echo", b"foxtrot", b"golf"]
    out = b""
    while len(out) < n:
        out += rnd.choice(pool) + b" "
    return out[:n]


def counting(n):
    return bytes(i & 0xFF for i in range(n))


def mbt(b):
    if not b:
        return 'b""'
    return 'b"' + "".join("\\x%02x" % c for c in b) + '"'


def mbt_array(items):
    if not items:
        return "[]"
    return "[\n    " + ",\n    ".join(items) + ",\n  ]"


cases = []

# The one example RFC 7692 §7.2.3.1 prints, which is what the encoder produces
# for the same message.
cases.append(
    (
        "RFC 7692 §7.2.3.1: the Hello example",
        15,
        False,
        segments(15, False, [b"Hello"]),
        [b"Hello"],
    )
)

# One message at a time, sizes chosen around the places DEFLATE and the frame
# layer change shape: the empty message, one octet, a length that fits in the
# seven-bit form, the boundary of each longer form.
for n in [0, 1, 5, 17, 125, 126, 127, 128, 255]:
    cases.append(
        (
            "one text message of %d octets" % n,
            15,
            False,
            segments(15, False, [words(n)]),
            [words(n)],
        )
    )

# A thousand octets of text: zlib reaches for a dynamic block here, so this is
# the case that reads the code-length code.
cases.append(
    (
        "one text message of 1024 octets",
        15,
        False,
        segments(15, False, [words(1024)]),
        [words(1024)],
    )
)

# Binary that barely compresses, which is the other end of the match finder.
cases.append(
    (
        "one binary message of 256 octets",
        15,
        False,
        segments(15, False, [counting(256)]),
        [counting(256)],
    )
)

# Level 0: stored blocks, the type a reader must handle and an encoder here
# never writes.
cases.append(
    (
        "one message in stored blocks",
        15,
        False,
        segments(15, False, [words(300)], level=0),
        [words(300)],
    )
)

# Context takeover: four messages whose later ones repeat the first, so the
# segments only decode if the window survives between them.
takeover = [words(200, 3), words(160, 4), words(200, 3), words(40, 5)]
cases.append(
    (
        "four messages sharing one window",
        15,
        True,
        segments(15, True, takeover),
        takeover,
    )
)

# A window that was negotiated down, both ways round.
small = [words(300, 7), words(300, 7)]
cases.append(("a nine-bit window", 9, False, segments(9, False, small), small))
cases.append(("a twelve-bit window", 12, False, segments(12, False, small), small))
cases.append(
    ("a nine-bit window kept across messages", 9, True, segments(9, True, small), small)
)

body = []
for name, bits, takeover, segs, messages in cases:
    body.append(
        "  (\n    %s,\n    %d,\n    %s,\n    %s,\n    %s,\n  )"
        % (
            '"%s"' % name.replace(chr(34), chr(92) + chr(34)),
            bits,
            "true" if takeover else "false",
            mbt_array([mbt(s) for s in segs]),
            mbt_array([mbt(m) for m in messages]),
        )
    )

text = '''// Copyright 2026 Leo Cheng
// SPDX-License-Identifier: Apache-2.0

// Generated by scripts/gen_deflate_vectors.py from zlib. Do not edit.
//
// Each case is a name, the window in bits, whether the window survives a message
// boundary, the wire segments one connection would carry (each with the
// four-octet tail of RFC 7692 §7.2.1 already stripped), and the message each
// segment decompresses to.

///|
pub let vectors : Array[(String, Int, Bool, Array[Bytes], Array[Bytes])] = [
%s,
]
''' % ",\n".join(body)

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write(text)
print("wrote %s: %d cases" % (OUT, len(cases)))
