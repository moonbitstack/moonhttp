#!/usr/bin/env python3
"""Turn scripts/cache-tests.json into the vectors the cache package is tested on.

The JSON is what `scripts/gen_cache_vectors.mjs` extracted from the cache-tests
suite; this writes it as MoonBit. One case is one question the suite asks: a
response a cache was given, the pause before the next request, that request, and
what it must be answered with (`cached`, `not_cached`, `etag_validated`,
`lm_validated`).
"""

import json

SRC = "scripts/cache-tests.json"
OUT = "src/cache/vectors_test.mbt"


def mbt(text):
    out = []
    for ch in text:
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append("\\x%02x" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def pairs(items):
    if not items:
        return "[]"
    body = ", ".join("(%s, %s)" % (mbt(name), mbt(value)) for name, value in items)
    return "[" + body + "]"


cases = json.load(open(SRC, encoding="utf-8"))
lines = []
for case in cases:
    lines.append(
        "  {\n"
        "    name: %s,\n"
        "    expect: %s,\n"
        "    status: %d,\n"
        "    pause: %d,\n"
        "    response: %s,\n"
        "    setup: %s,\n"
        "    request: %s,\n"
        "  },"
        % (
            mbt("%s/%s" % (case["suite"], case["id"])),
            mbt(case["expect"]),
            case["status"],
            case["pause"],
            pairs(case["response"]),
            pairs(case["setup_request"]),
            pairs(case["check_request"]),
        )
    )

text = '''// Copyright 2026 Leo Cheng
// SPDX-License-Identifier: Apache-2.0

// Generated by scripts/gen_cache_vectors.py from scripts/cache-tests.json, which
// scripts/gen_cache_vectors.mjs extracted from the cache-tests suite. Do not edit.
//
// Each case is one question the suite asks a cache: a response it was given, the
// pause before the next request, that request, and what must happen next.

///|
struct Case {
  /// `suite/id`, so a failure names the case it came from.
  name : String
  /// `cached`, `not_cached`, `etag_validated` or `lm_validated`.
  expect : String
  status : Int32
  /// Seconds the suite waits between the two requests.
  pause : Int32
  /// The response the cache was given.
  response : Array[(String, String)]
  /// The request that produced it.
  setup : Array[(String, String)]
  /// The request it must then answer.
  request : Array[(String, String)]
}

///|
let cases : Array[Case] = [
%s
]
''' % "\n".join(lines)

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write(text)
print("wrote %s: %d cases" % (OUT, len(cases)))
